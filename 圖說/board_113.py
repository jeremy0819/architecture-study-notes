def draw_plan(s, f, sp):
    s.rect(f.X(-66), f.Y(-30), f.L(202), f.L(30), fill=LGREY)          # 北 30M
    s.rect(f.X(-66), f.Y(D_), f.L(202), f.L(15), fill=LGREY)           # 南 15M
    s.rect(f.X(W_), f.Y(-30), f.L(20), f.L(D_+45), fill=LGREY)         # 東 20M
    # 西側國小（基地外・緊鄰）
    s.rect(f.X(-62), f.Y(-30), f.L(62), f.L(D_+45), fill="#eef1ea", stroke=GREEN, stroke_width=0.4)
    for gx in range(-56, -6, 16):
        s.rect(f.X(gx), f.Y(4), f.L(12), f.L(30), fill="#e2e8dc", stroke=GREEN, stroke_width=0.3)
    s.txt(f.X(-31), f.Y(-6), "西鄰　國民小學（基地外・後門接送）", 3.4, GREEN, "middle", "bold")
    s.txt(f.X(-31), f.Y(42), "該側全線不設車行出入口——人車安全第一", 2.7, RED, "middle", "bold")
    # 北側商業（基地外）
    s.rect(f.X(-4), f.Y(-46), f.L(78), f.L(14), fill="#ece9e3", stroke=GREY, stroke_width=0.35)
    s.txt(f.X(35), f.Y(-38), "對側商業 12 層（1 樓餐廳）", 3.2, "#555", "middle", "bold")
    s.txt(f.X(35), f.Y(-16), "北側 30 M 道路｜主人流・市集主入口", 3.2, "#555", "middle")
    # 東側住宅街廓（基地外）
    for gy in range(-24, 46, 18):
        s.rect(f.X(W_+24), f.Y(gy), f.L(30), f.L(13), fill="#ece9e3", stroke=GREY, stroke_width=0.3)
    s.txt(f.X(W_+39), f.Y(52), "東側對街住宅街廓", 3.0, "#555", "middle")
    s.txt(f.X(W_+10), f.Y(D_*0.5), "東側 20 M 道路", 2.8, "#555", "middle", rot=-90)
    # 南側廟宇（基地外・道路對側，坐北朝南）
    s.rect(f.X(6), f.Y(D_+21), f.L(46), f.L(20), fill="#f5ece0", stroke=TAN, stroke_width=0.5)
    s.txt(f.X(29), f.Y(D_+33), "廟宇（坐北朝南）", 3.4, "#8a6a1f", "middle", "bold")
    s.txt(f.X(29), f.Y(D_+38), "廟埕在南側（背對本案）", 2.5, RED, "middle")
    for tx in range(10, 50, 7):
        s.circ(f.X(tx), f.Y(D_+17), f.L(4.0), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.3)
    s.txt(f.X(29), f.Y(D_+23.5), "廟宇北側既存樹群與休憩庭園（道路對側・基地外）", 2.7, GREEN, "middle", "bold")
    s.txt(f.X(29), f.Y(D_+10), "南側 15 M 道路", 2.8, "#555", "middle")
    # 基地
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=0.9)
    s.txt(f.X(-62), f.Y(-22), "基地界線　東西 70 M／南北 50 M（市場用地）", 3.0, INK, weight="bold")
    s.txt(f.X(-62), f.Y(-17.5), "A＝70×50＝3,500 ㎡〔題目給定〕；東北轉角截角依題圖，未標尺寸不另扣除", 2.6, "#555")
    # 市集大廳
    x, y, w, h = MKT
    s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill="#f2e4c9", stroke=INK, stroke_width=0.7)
    s.txt(f.X(x+w/2), f.Y(y+h/2)-2.4, "市集大廳（1F 生鮮 30 攤・熟食）", 3.6, INK, "middle", "bold")
    s.txt(f.X(x+w/2), f.Y(y+h/2)+1.6, "2F 快閃／社工站・管理辦公", 2.8, "#555", "middle")
    s.txt(f.X(x+w/2), f.Y(y+h/2)+5.4, "投影 1,000 ㎡｜非住宅計容積 1,400 ㎡", 2.5, "#555", "middle")
    for i in range(1, 5):
        s.line(f.X(x+w*i/5), f.Y(y), f.X(x+w*i/5), f.Y(y+h), stroke=GREY, stroke_width=0.25)
    # 社宅棟（3F 以上投影）
    rx, ry_, rw, rh = RES
    s.rect(f.X(rx), f.Y(ry_), f.L(rw), f.L(rh), fill="none", stroke="#7a5ea8",
           stroke_width=0.9, stroke_dasharray="3.2 1.8")
    leader(s, f.X(rx+rw), f.Y(ry_+2), f.X(rx+rw)+30, f.Y(ry_)-14,
           "社會住宅棟 3F–8F 投影（150 戶）・獨立門廳與門禁", 2.8, "#7a5ea8", "start", "bold")
    # 獨立門廳
    s.rect(f.X(60), f.Y(9), f.L(8), f.L(18), fill="#e6dced", stroke=INK, stroke_width=0.6)
    s.txt(f.X(64), f.Y(18), "社宅門廳", 2.8, INK, "middle", "bold", rot=-90)
    # 廟埕共生廣場（南側・快閃市集兼滯洪）
    s.poly(f.P([(0, 33), (W_, 33), (W_, D_), (0, D_)]), fill="url(#plaza)", opacity=0.5,
           stroke=TAN, stroke_width=0.4)
    s.txt(f.X(35), f.Y(38.5), "快閃市集廣場（廟埕共生）", 4.6, "#8a6a1f", "middle", "bold")
    s.txt(f.X(35), f.Y(43), "無建物・地震臨時避難集結地・假日快閃攤位模矩 3×3 M", 2.6, "#8a6a1f", "middle")
    s.txt(f.X(35), f.Y(47), "透水鋪面＋地下滯蓄槽（人車區不得受淹）", 2.5, BLUE, "middle")
    for xx in range(6, 68, 8):
        s.circ(f.X(xx), f.Y(31), f.L(3.2), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.2)
    # 出入口
    for x0, y0, lab, col, an in [
            (34, 0, "市集主入口－北側 30 M 主人流", RED, "end"),
            (64, 14, "社宅獨立門廳－東側安靜面", "#7a5ea8", "end"),
            (35, 50, "廟埕廣場人行－南側對廟宇綠庭", RED, "start"),
            (70, 40, "地下車道出入口－東側 20 M（避開國小）", BLUE, "end"),
            (10, 8, "生鮮卸貨－北側西端、與人流錯開", "#555", "end")]:
        px, py = f.X(x0), f.Y(y0)
        ox = 16 if an == "start" else -16
        leader(s, px, py, px+ox, py-5, lab, 2.6, col, an, "bold")
    # 開挖
    ex, ey, ew, eh = EXC
    s.path(f'M {f.X(ex):.2f} {f.Y(ey):.2f} L {f.X(ex+ew):.2f} {f.Y(ey):.2f} '
           f'L {f.X(ex+ew):.2f} {f.Y(ey+eh):.2f} L {f.X(ex):.2f} {f.Y(ey+eh):.2f} Z',
           fill="none", stroke=RED, stroke_width=0.7, stroke_dasharray="2.6 1.6")
    s.txt(f.X(ex+2), f.Y(ey+eh-4.5), "地下開挖範圍（B1 停車・防空避難）", 2.8, RED, weight="bold")
    s.txt(f.X(ex+2), f.Y(ey+eh-1), f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%〔題目點名須標示〕", 2.4, RED)
    # 剖面線
    s.line(f.X(-28), f.Y(18), f.X(W_+18), f.Y(18), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(-31), f.Y(19), "A", 4.0, INK, "middle", "bold")
    s.txt(f.X(W_+21), f.Y(19), "A'", 4.0, INK, "middle", "bold")
    s.line(f.X(30), f.Y(-32), f.X(30), f.Y(D_+44), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(30), f.Y(-35), "B", 4.0, INK, "middle", "bold")
    s.txt(f.X(30), f.Y(D_+49), "B'", 4.0, INK, "middle", "bold")

