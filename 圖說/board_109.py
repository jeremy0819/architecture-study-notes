    s.raw(f'<rect x="{f.X(60):.2f}" y="{f.Y(112):.2f}" width="{f.L(80):.2f}" height="{f.L(52):.2f}" '
          f'rx="{f.L(26):.2f}" fill="#f6efe4" stroke="{TAN}" stroke-width="0.7"/>')
    s.raw(f'<rect x="{f.X(68):.2f}" y="{f.Y(120):.2f}" width="{f.L(64):.2f}" height="{f.L(36):.2f}" '
          f'rx="{f.L(18):.2f}" fill="#e8f0e0" stroke="{GREEN}" stroke-width="0.5"/>')
    s.txt(f.X(100), f.Y(138), "200 M 跑道（題目給定）", 3.4, "#8a6a1f", "middle", "bold")
    s.txt(f.X(100), f.Y(143), "內場草地兼避難集結", 2.6, GREEN, "middle")
    s.txt(f.X(100), f.Y(169), "運動場置較平處，順坡整地、周邊設截水溝", 2.7, "#555", "middle")
