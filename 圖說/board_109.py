    ex, ey, ew, eh = EXC
    s.path(f'M {f.X(ex):.2f} {f.Y(ey):.2f} L {f.X(ex+ew):.2f} {f.Y(ey):.2f} '
           f'L {f.X(ex+ew):.2f} {f.Y(ey+eh):.2f} L {f.X(ex):.2f} {f.Y(ey+eh):.2f} Z',
           fill="none", stroke=RED, stroke_width=0.8, stroke_dasharray="3 1.8")
    s.txt(f.X(ex+2), f.Y(ey+8), "地下停車開挖範圍（75 輛）", 2.9, RED, weight="bold")
    s.txt(f.X(ex+2), f.Y(ey+13), f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%", 2.5, RED)
    s.txt(f.X(ex+2), f.Y(ey+18), "地面另設 25 輛（含接送）——非其餘一律地下", 2.5, RED)
    # 剖面線
    s.line(f.X(-80), f.Y(45), f.X(280), f.Y(45), stroke=INK, stroke_width=0.6,
           stroke_dasharray="6 2 1.6 2")
    s.txt(f.X(-86), f.Y(46), "A", 4.2, INK, "middle", "bold")
    s.txt(f.X(286), f.Y(46), "A'", 4.2, INK, "middle", "bold")
    s.line(f.X(64), f.Y(-24), f.X(64), f.Y(222), stroke=INK, stroke_width=0.6,
           stroke_dasharray="6 2 1.6 2")
