    s.rect(f.X(-15), f.Y(-10), f.L(15), f.L(D_+20), fill=LGREY)      # 西 15M
    s.rect(f.X(W_), f.Y(-10), f.L(30), f.L(D_+20), fill=LGREY)       # 東 30M
    s.rect(f.X(-15), f.Y(-10), f.L(W_+45), f.L(10), fill=LGREY)      # 北 10M
    s.rect(f.X(-15), f.Y(D_), f.L(W_+45), f.L(10), fill=LGREY)       # 南 10M
    s.txt(f.X(W_/2), f.Y(-4), "北側 10 M 道路", 3.4, "#555", "middle")
    s.txt(f.X(W_/2), f.Y(D_+6.5), "南側 10 M 道路", 3.4, "#555", "middle")
    s.txt(f.X(-7.5), f.Y(D_/2), "西側 15 M 道路", 3.0, "#555", "middle", rot=-90)
    s.txt(f.X(W_+15), f.Y(D_/2), "東側 30 M 道路", 3.0, "#555", "middle", rot=-90)
    # 西側危老高層（基地外）
    for gy in range(-4, 200, 26):
        s.rect(f.X(-76), f.Y(gy), f.L(58), f.L(19), fill="#dcd8d0", stroke=GREY, stroke_width=0.35)
        s.txt(f.X(-47), f.Y(gy+11), "12–16F", 2.6, "#777", "middle")
    s.txt(f.X(-47), f.Y(-14), "西側已依危老重建為 12–16 層（基地外）", 3.2, RED, "middle", "bold")
    s.txt(f.X(-47), f.Y(212), "校園低層退讓、爭取學童日照", 3.0, RED, "middle", "bold")
    # 東側對街 3–5 層社區（基地外）
    for gy in range(-4, 200, 22):
        s.rect(f.X(236), f.Y(gy), f.L(46), f.L(15), fill="#ece9e3", stroke=GREY, stroke_width=0.3)
    s.txt(f.X(259), f.Y(-14), "東側對街低矮社區（尚未重建）", 3.0, "#555", "middle", "bold")
    s.txt(f.X(259), f.Y(212), "校園綠環同時為社區共享步道", 2.8, GREEN, "middle")
    # 基地
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=1.0)
    s.txt(f.X(0), f.Y(-16), "基地界線　完整街廓 約 200 M × 200 M ＝ 40,000 ㎡（4 公頃・機關用地）", 3.2, INK, weight="bold")
    s.txt(f.X(0), f.Y(-21), "北高南低、坡度約 1%〔題目給定〕；建蔽率與容積率題目未給 → 圖上明寫未指定", 2.7, RED)
    # 綠環（周邊 15 M 連續林帶與步道）
    s.poly(f.P([(0, 0), (W_, 0), (W_, D_), (0, D_)]), fill="none", stroke=GREEN,
           stroke_width=0.4, stroke_dasharray="3 2")
    s.poly(f.P([(15, 15), (W_-15, 15), (W_-15, D_-15), (15, D_-15)]), fill="none",
           stroke=GREEN, stroke_width=0.6, stroke_dasharray="3 2")
    for xx in range(6, 198, 13):
        s.circ(f.X(xx), f.Y(7), f.L(4.6), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.22)
        s.circ(f.X(xx), f.Y(193), f.L(4.6), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.22)
    for yy in range(20, 190, 13):
        s.circ(f.X(7), f.Y(yy), f.L(4.6), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.22)
        s.circ(f.X(193), f.Y(yy), f.L(4.6), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.22)
    s.txt(f.X(100), f.Y(11), "連續綠環：15 M 林帶＋步道（緩衝、通學、社區共享）", 3.2, GREEN, "middle", "bold")
