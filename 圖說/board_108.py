def draw_plan(s, f, sp):
    # 周邊道路
    s.rect(f.X(-40), f.Y(-6), f.L(40), f.L(D_+24), fill=LGREY)       # 西 40M
    s.rect(f.X(-40), f.Y(-6), f.L(W_+70), f.L(6), fill=LGREY)        # 北 6M 巷
    s.rect(f.X(-40), f.Y(D_), f.L(W_+70), f.L(9), fill=LGREY)        # 南 9M 巷
    s.txt(f.X(-20), f.Y(D_/2), "西側 40 M 道路（大眾運輸方便・TOD 人流）", 3.2, "#555", "middle", rot=-90)
    s.txt(f.X(W_/2), f.Y(-2.4), "北側 6 M 巷道（車行・服務・垃圾清運）", 2.9, "#555", "middle")
    s.txt(f.X(W_/2), f.Y(D_+6), "南側 9 M 巷道", 2.9, "#555", "middle")
    # 對側 7–12 層住商（西）
    for gy in range(-4, 34, 14):
        s.rect(f.X(-70), f.Y(gy), f.L(26), f.L(11), fill="#dcd8d0", stroke=GREY, stroke_width=0.35)
    s.txt(f.X(-57), f.Y(-10), "對側住商 7–12 層", 3.0, "#555", "middle", "bold")
    # 南側三角形社區公園（基地外）
    s.poly(f.P([(2, 41), (58, 41), (30, 74)]), fill="url(#tree)", stroke=GREEN, stroke_width=0.6)
    s.txt(f.X(30), f.Y(50), "三角形社區公園（基地外）", 3.6, GREEN, "middle", "bold")
    s.txt(f.X(30), f.Y(55), "英雄條件：主開放面朝此", 2.9, GREEN, "middle", "bold")
    s.txt(f.X(30), f.Y(60), "隔 9 M 巷道，借景不計入 A、不得當法定空地", 2.5, RED, "middle")
    s.line(f.X(30), f.Y(D_), f.X(30), f.Y(41), stroke=RED, stroke_width=0.9, stroke_dasharray="3 1.6")
    s.txt(f.X(32), f.Y(39.5), "安全穿越（行穿線＋路口縮寬）", 2.6, RED, "start", "bold")
    # 東側老舊公寓（基地外）
    for gy in range(-2, 32, 12):
        s.rect(f.X(W_+6), f.Y(gy), f.L(30), f.L(9), fill="#ece9e3", stroke=GREY, stroke_width=0.3)
    s.txt(f.X(W_+21), f.Y(-8), "東側 4–5 層老舊公寓", 3.0, "#555", "middle", "bold")
    s.txt(f.X(W_+21), f.Y(40), "量體退讓、檐高呼應", 2.7, "#555", "middle")
    # 基地
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=0.95)
    s.txt(f.X(0), f.Y(-9.5), "基地界線　60 M × 32 M ＝ 1,920 ㎡（住宅區）", 3.2, INK, weight="bold")
    s.txt(f.X(0), f.Y(-14), "A＝1,920 ㎡〔題目給定〕；空間需求 900 坪＝2,975.21 ㎡（1 坪＝400/121）", 2.7, RED)
    # 主量體
    x, y, w, h = MAIN
    s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill="#e6dced", stroke=INK, stroke_width=0.75)
    s.line(f.X(44), f.Y(y), f.X(44), f.Y(y+h), stroke=INK, stroke_width=0.5, stroke_dasharray="2 1.4")
    s.txt(f.X(24), f.Y(9.5), "課程・親子・共餐開放廚房・講座・祈禱室", 3.2, INK, "middle", "bold")
    s.txt(f.X(24), f.Y(13.5), "多媒體展示販售｜營運辦公　1–4F", 2.7, "#555", "middle")
    s.txt(f.X(24), f.Y(17), "投影 832 ㎡｜G＝832×4F＝3,328 ㎡", 2.5, "#555", "middle")
    s.txt(f.X(50), f.Y(8.5), "緊急安置", 2.8, "#7a5ea8", "middle", "bold")
    s.txt(f.X(50), f.Y(12), "心理諮商", 2.8, "#7a5ea8", "middle", "bold")
    s.txt(f.X(50), f.Y(15.5), "（私密・獨立出入口）", 2.3, "#7a5ea8", "middle")
    # 南側前庭（面公園）
    s.poly(f.P([(0, 19), (W_, 19), (W_, D_), (0, D_)]), fill="url(#plaza)", opacity=0.5,
           stroke=TAN, stroke_width=0.45)
    s.txt(f.X(24), f.Y(25.5), "面公園前庭・半戶外共享客廳", 3.8, "#8a6a1f", "middle", "bold")
    s.txt(f.X(24), f.Y(29.8), "地震臨時避難集合｜地面層抬高 +0.6 M 防淹｜自行車位 ≥10", 2.5, "#8a6a1f", "middle")
    for tx in range(6, 58, 8):
        s.circ(f.X(tx), f.Y(20.5), f.L(2.8), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.2)
    # 出入口
    for x0, y0, lab, col, an, ox, oy in [
            (0, 22, "主人行入口－西南迎 40 M 道路 TOD 人流", RED, "end", -20, -6),
            (30, 32, "大廳・前庭－面三角公園（穿越至公園）", RED, "start", 4, 6),
            (52, 0, "緊急安置專用出入口－北側 6 M（私密、可獨立進出）", "#7a5ea8", "start", 6, -12),
            (16, 0, "車行・垃圾清運－北側 6 M 巷道", BLUE, "end", -16, -8),
            (60, 26, "地下車道出入口－東端", "#555", "start", 6, 6)]:
        px, py = f.X(x0), f.Y(y0)
        leader(s, px, py, px+f.L(0)+ox*1.0, py+oy*1.0, lab, 2.6, col, an, "bold")
    # 開挖
    ex, ey, ew, eh = EXC
    s.path(f'M {f.X(ex):.2f} {f.Y(ey):.2f} L {f.X(ex+ew):.2f} {f.Y(ey):.2f} '
           f'L {f.X(ex+ew):.2f} {f.Y(ey+eh):.2f} L {f.X(ex):.2f} {f.Y(ey+eh):.2f} Z',
           fill="none", stroke=RED, stroke_width=0.75, stroke_dasharray="2.6 1.6")
    leader(s, f.X(ex), f.Y(ey+eh), f.X(ex)-26, f.Y(ey+eh)+14,
           "地下開挖範圍（B1 汽 12＋機 10＋防空避難）", 2.7, RED, "end", "bold")
    s.txt(f.X(ex)-26, f.Y(ey+eh)+18.6, f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%〔題目未給上限〕", 2.4, RED, "end")
    # 剖面線
    s.line(f.X(-74), f.Y(11), f.X(W_+40), f.Y(11), stroke=INK, stroke_width=0.55,
           stroke_dasharray="5 1.8 1.4 1.8")
    s.txt(f.X(-78), f.Y(12), "A", 4.2, INK, "middle", "bold")
    s.txt(f.X(W_+44), f.Y(12), "A'", 4.2, INK, "middle", "bold")
    s.line(f.X(30), f.Y(-12), f.X(30), f.Y(78), stroke=INK, stroke_width=0.55,
           stroke_dasharray="5 1.8 1.4 1.8")
    s.txt(f.X(30), f.Y(-16), "B", 4.2, INK, "middle", "bold")
    s.txt(f.X(30), f.Y(82), "B'", 4.2, INK, "middle", "bold")

