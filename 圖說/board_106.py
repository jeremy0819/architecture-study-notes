    s.txt(f.X(28), f.Y(50), "樹下遮蔭・室外家具・地震臨時避難集合", 2.6, "#8a6a1f", "middle")
    s.txt(f.X(28), f.Y(54.2), "建築退讓、不進樹冠投影範圍", 2.5, RED, "middle", "bold")
