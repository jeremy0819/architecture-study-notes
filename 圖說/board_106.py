    for name, spec, x, y, w, h, col in BLK:
        s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill=col, stroke=INK, stroke_width=0.75)
        s.txt(f.X(x+w/2), f.Y(y+h/2)-1.4, name, 2.9 if len(name) > 10 else 3.4, INK, "middle", "bold")
        s.txt(f.X(x+w/2), f.Y(y+h/2)+2.6, spec, 2.6, "#555", "middle")
    s.txt(f.X(19), f.Y(14), "單層化動線・近電梯・平緩坡道・防滑・近保健室", 2.5, "#666", "middle")
