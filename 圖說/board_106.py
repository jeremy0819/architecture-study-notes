    s.rect(f.X(-70), f.Y(-20), f.L(188), f.L(20), fill=LGREY)
    s.txt(f.X(W_/2), f.Y(-9), "北側 20 M 道路（主要臨路）", 3.2, "#555", "middle")
    # 對側街廓
    for gx in range(-66, 110, 18):
        s.rect(f.X(gx), f.Y(-44), f.L(14), f.L(20), fill="#ece9e3", stroke=GREY, stroke_width=0.3)
    s.txt(f.X(W_/2), f.Y(-48), "對側舊社區（低層・排水系統老舊）", 3.0, "#555", "middle", "bold")
