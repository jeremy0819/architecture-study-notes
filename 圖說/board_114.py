    ex, ey, ew, eh = EXC
    s.path(f'M {f.X(ex):.2f} {f.Y(ey):.2f} L {f.X(ex+ew):.2f} {f.Y(ey):.2f} '
           f'L {f.X(ex+ew):.2f} {f.Y(ey+eh):.2f} L {f.X(ex):.2f} {f.Y(ey+eh):.2f} Z',
           fill="none", stroke=RED, stroke_width=0.7, stroke_dasharray="2.6 1.6")
    s.txt(f.X(ex+1.5), f.Y(ey+eh+3.5), "地下開挖範圍（B1 停車）", 2.8, RED, weight="bold")
    s.txt(f.X(ex+1.5), f.Y(ey+eh+7), f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%〔題目點名須標〕", 2.4, RED)
    # 剖面線
    s.line(f.X(-47), f.Y(20), f.X(82), f.Y(20), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(-50), f.Y(21), "A", 4.0, INK, "middle", "bold")
    s.txt(f.X(85), f.Y(21), "A'", 4.0, INK, "middle", "bold")
    s.line(f.X(18), f.Y(-22), f.X(18), f.Y(100), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(18), f.Y(-25), "B", 4.0, INK, "middle", "bold")
    s.txt(f.X(18), f.Y(105), "B'", 4.0, INK, "middle", "bold")

