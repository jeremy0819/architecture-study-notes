# 基地：北寬 50 M（深 54 M）＋南窄 32 M（深 28 M），總深 82 M
SITE = [(0, 0), (50, 0), (50, 54), (32, 54), (32, 82), (0, 82)]
A = 50*54 + 32*28                 # 3,596 ㎡〔圖示量取・與正文約 3,600 ㎡ 並存，分母不混用〕
# 量體退向東／中，西側整條 12 M 留給面園道的帶狀開放空間（題目點名）
PARK = (12, 5, 33, 27)            # 停車棟 891 ㎡
SPORT = (12, 34, 20, 44)          # 運動棟 880 ㎡
EXC = (10, 5, 35, 47)             # 1,645 ㎡
D_AREA = EXC[2]*EXC[3]
B = PARK[2]*PARK[3] + SPORT[2]*SPORT[3]        # 2,003
F_SPORT = SPORT[2]*SPORT[3]*5                  # 4,400（計容積・多目標）
F_CAP = A*4.00/3                               # 多目標一般門檻 ≤ 總容積 1/3
NEED = (300+200+500+300)*400/121               # ≥1,300 坪 ≈ 4,297.52 ㎡
assert B <= A*0.80 and B <= A*0.60, B
assert NEED <= F_SPORT <= F_CAP, (NEED, F_SPORT, F_CAP)
CARS = int((PARK[2]*PARK[3]*7)//40)            # 6F 地上＋B1

