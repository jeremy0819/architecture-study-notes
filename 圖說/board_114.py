    s.rect(f.X(13), f.Y(32), f.L(6), f.L(2), fill="#f2c9a0", stroke=RED, stroke_width=0.6)
    leader(s, f.X(19), f.Y(33), f.X(40), f.Y(35), "極限攀岩牆－串接兩棟・兼立體地標", 2.6, RED, "start", "bold")
    # 東南側戶外運動場（南段窄基地外之空地）
