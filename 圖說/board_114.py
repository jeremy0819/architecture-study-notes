    for gy in range(-10, 86, 16):
        s.rect(f.X(53), f.Y(gy), f.L(26), f.L(12), fill="#ece9e3", stroke=GREY, stroke_width=0.3)
    s.txt(f.X(66), f.Y(92), "東側商業區　老舊 3–5 層街屋（緊臨道路設騎樓）", 3.0, "#555", "middle")
    # 北 7M 道路
    s.rect(f.X(-46), f.Y(-7), f.L(140), f.L(7), fill=LGREY)
    s.txt(f.X(25), f.Y(-9), "北側 7 M 道路（對側 3–4 層・轉角 7 層）", 2.8, "#555", "middle")
    # 南 20M 道路
    s.rect(f.X(-46), f.Y(82), f.L(140), f.L(20), fill=LGREY)
    s.txt(f.X(16), f.Y(94), "南側 20 M 道路（2.5＋15＋2.5）", 2.8, "#555", "middle")
    # 西 12M 道路（2 步道＋6 車道＋4 步道）
    s.rect(f.X(-12), f.Y(-7), f.L(12), f.L(109), fill=LGREY)
    s.txt(f.X(-6), f.Y(40), "西側 12 M 道路（2 步道＋6 車道＋4 步道）", 2.7, "#555", "middle", rot=-90)
    s.txt(f.X(-6), f.Y(74), "假日可封街為徒步街〔方案〕", 2.5, RED, "middle", rot=-90)
    # 33M 園道（基地外・道路對側）
    s.rect(f.X(-45), f.Y(-7), f.L(33), f.L(109), fill="#e9f0e2", stroke=GREEN, stroke_width=0.5)
    s.rect(f.X(-35.5), f.Y(-7), f.L(14), f.L(109), fill="url(#water)", stroke=BLUE, stroke_width=0.5)
    s.txt(f.X(-40.5), f.Y(44), "33 M 園道（基地外・隔 12 M 道路）", 3.0, GREEN, "middle", "bold", rot=-90)
    s.txt(f.X(-28.5), f.Y(44), "中央 14 M 生態排水渠（水位低道路約 2 M）", 2.8, BLUE, "middle", "bold", rot=-90)
    for gy in range(-2, 96, 11):
        s.circ(f.X(-17), f.Y(gy), f.L(3.4), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.22)
    # 跨越：小橋／石階
    s.line(f.X(-12), f.Y(30), f.X(-45), f.Y(30), stroke=RED, stroke_width=0.9, stroke_dasharray="3 1.6")
    s.txt(f.X(-28), f.Y(28), "小橋／石階跨排水渠－與園道「部分連接」（題目點名）", 2.6, RED, "middle", "bold")
    # 基地
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=0.9)
    s.txt(f.X(0), f.Y(-14), "基地界線　北寬 50 M（深 54 M）＋南窄 32 M（深 28 M）", 3.0, INK, weight="bold")
    s.txt(f.X(0), f.Y(-18.4), "A＝50×54＋32×28＝3,596 ㎡〔圖示量取〕；正文約 3,600 ㎡——分母不混用", 2.6, RED)
    # 退縮帶（西、南各 4 M 無遮簷）＋西側 12 M 帶狀開放空間
    s.poly(f.P([(0, 0), (4, 0), (4, 78), (32, 78), (32, 82), (0, 82)]),
           fill="#f3f1ea", stroke=GREY, stroke_width=0.45, stroke_dasharray="2 1.4")
    s.poly(f.P([(4, 0), (12, 0), (12, 78), (4, 78)]), fill="url(#plaza)", opacity=0.5,
           stroke=TAN, stroke_width=0.4)
    s.txt(f.X(2), f.Y(52), "西側退縮 4 M 無遮簷", 2.4, "#666", "middle", rot=-90)
    s.txt(f.X(8), f.Y(46), "西側主視覺廣場・帶狀商業市集・眺望平台（面園道）", 3.0,
          "#8a6a1f", "middle", "bold", rot=-90)
    s.txt(f.X(16), f.Y(80.4), "南側退縮 4 M 無遮簷帶狀開放空間（騎樓須退到本帶之外）", 2.5, "#666", "middle")
    # 北側加大退縮街角廣場
    s.poly(f.P([(12, 0), (50, 0), (50, 5), (12, 5)]), fill="url(#plaza)", opacity=0.45,
           stroke=TAN, stroke_width=0.35)
    s.txt(f.X(31), f.Y(3.2), "北側加大退縮・街角廣場", 2.6, "#8a6a1f", "middle", "bold")
    # 停車棟
    x, y, w, h = PARK
    s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill="#d9dde2", stroke=INK, stroke_width=0.7)
    s.txt(f.X(x+w/2), f.Y(y+h/2)-3.0, "立體停車棟　地上 6F（≤18 M）＋B1", 3.6, INK, "middle", "bold")
    s.txt(f.X(x+w/2), f.Y(y+h/2)+1.0, f"投影 891 ㎡｜雙螺旋坡道｜約 {CARS} 輛〔方案・刻意不衝滿〕", 2.6, "#555", "middle")
    s.txt(f.X(x+w/2), f.Y(y+h/2)+4.8, "機車位＝汽車位數量並分流；親子／無障礙／電動車位分層標示", 2.5, "#555", "middle")
    s.txt(f.X(x+w/2), f.Y(y+h/2)+8.6, "停車樓地板依技則得不計入容積", 2.5, BLUE, "middle", "bold")
