    s.txt(f.X(x2+w2/2), f.Y(y2+h2/2)+1.0, "投影 880 ㎡｜計容積 4,400 ㎡", 2.7, "#555", "middle")
    s.txt(f.X(x2+w2/2), f.Y(y2+h2/2)+4.8, "體適能／韻律／桌羽壁球（淨高 6.1 M＋結構設備）", 2.5, "#555", "middle")
    s.txt(f.X(x2+w2/2), f.Y(y2+h2/2)+8.6, "1F 健康顧問＋健康餐飲，對外營業接社區", 2.5, "#555", "middle")
