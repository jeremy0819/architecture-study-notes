# L 形：50×59 外框扣 25×14 凹口（圖推概算）
SITE = [(0, 0), (25, 0), (25, 14), (50, 14), (50, 59), (0, 59)]
A = 50*59 - 25*14                    # 2,600 ㎡
BLK = [("共享辦公・交流棟", "1F 共享交流／2–4F 辦公住辦", 2, 17, 44, 16, "#e6dced"),
       ("住宅棟", "1–6F 住宅 50 戶", 30, 33, 16, 23, "#d6e6f2")]
FOOT = sum(w*h for *_, x, y, w, h, c in BLK)      # 1,072
G = 44*16*4 + 16*23*6                              # 5,024
EXC = [(4, 17, 42, 17), (28, 34, 18, 22)]          # L 形開挖，避開中庭老樹
D_AREA = sum(w*h for _, _, w, h in EXC)            # 1,110
assert FOOT <= A*0.45 and G <= A*2.25, (FOOT, G)

def draw_plan(s, f, sp):
    # 3 M 無遮簷人行道環基地（題目給定）
    s.poly(f.P([(-3.6, -3.6), (28.6, -3.6), (28.6, 10.4), (53.6, 10.4), (53.6, 62.6), (-3.6, 62.6)]),
           fill="#f3f1ea", stroke=GREY, stroke_width=0.35)
    # 西南 埤塘公園（基地外）
    s.raw(f'<ellipse cx="{f.X(-34):.2f}" cy="{f.Y(64):.2f}" rx="{f.L(34):.2f}" ry="{f.L(26):.2f}" '
          f'fill="url(#water)" stroke="{BLUE}" stroke-width="0.6"/>')
    s.txt(f.X(-34), f.Y(62), "埤塘公園（基地外）", 3.6, BLUE, "middle", "bold")
    s.txt(f.X(-34), f.Y(67), "假日遊客多・本案主開放面", 2.7, BLUE, "middle")
    s.txt(f.X(-34), f.Y(71.5), "借景不計入 A，亦無用地控制權", 2.4, RED, "middle")
    for i, (tx, ty) in enumerate([(-8, 52), (-12, 60), (-6, 66), (-16, 46)]):
        s.circ(f.X(tx), f.Y(ty), f.L(4.0), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.25)
    # 東北 國小（基地外）
    s.rect(f.X(34), f.Y(-34), f.L(46), f.L(26), fill="#eef1ea", stroke=GREEN, stroke_width=0.45)
    s.txt(f.X(57), f.Y(-22), "國民小學（基地外・後門接送）", 3.2, GREEN, "middle", "bold")
    s.txt(f.X(57), f.Y(-17), "尖峰接送：設避車彎，人車分離", 2.6, RED, "middle")
    # 周邊街廓
    for gx in range(-40, 0, 16):
        s.rect(f.X(gx), f.Y(-30), f.L(12), f.L(18), fill="#ece9e3", stroke=GREY, stroke_width=0.3)
    s.txt(f.X(-24), f.Y(-8), "新開發都市・住商混合街廓", 2.8, "#555", "middle")
    # 基地
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=0.95)
    s.txt(f.X(-4), f.Y(-14), "基地界線　L 形：50 M × 59 M 外框扣 25 M × 14 M 凹口", 3.0, INK, weight="bold")
    s.txt(f.X(-4), f.Y(-9.6), "A＝50×59−25×14＝2,950−350＝2,600 ㎡〔圖推概算〕", 2.6, RED, weight="bold")
    s.txt(f.X(37.5), f.Y(7), "凹口 25 M × 14 M", 2.8, RED, "middle", "bold")
    s.txt(f.X(37.5), f.Y(11), "（不得漏扣）", 2.5, RED, "middle")
    # 量體
    for name, spec, x, y, w, h, col in BLK:
        s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill=col, stroke=INK, stroke_width=0.7)
        s.txt(f.X(x+w/2), f.Y(y+h/2)-1.6, name, 3.6, INK, "middle", "bold")
        s.txt(f.X(x+w/2), f.Y(y+h/2)+2.4, spec, 2.6, "#555", "middle")
    # 中庭（留既有樹）
    s.poly(f.P([(4, 35), (28, 35), (28, 55), (4, 55)]), fill="#f7f9f4",
           stroke=GREEN, stroke_width=0.45)
    for tx, ty in [(10, 40), (18, 44), (12, 50), (22, 39)]:
        s.circ(f.X(tx), f.Y(ty), f.L(4.4), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.3)
    s.txt(f.X(16), f.Y(53), "共享中庭（基地內既有樹保留為核心）", 2.8, GREEN, "middle", "bold")
    # 西南開放交流面
    s.poly(f.P([(0, 55), (28, 55), (28, 59), (0, 59)]), fill="url(#plaza)", opacity=0.55,
           stroke=TAN, stroke_width=0.4)
    s.txt(f.X(14), f.Y(57.6), "西南半戶外平台・面埤塘開放交流", 2.8, "#8a6a1f", "middle", "bold")
    # 出入口
    for x0, y0, lab, col, an in [
            (14, 59, "共享交流主入口－面西南埤塘", RED, "start"),
            (46, 20, "住辦門廳－東側安靜面", "#7a5ea8", "end"),
            (25, 7, "地下車道出入口－凹口側，避開國小接送", BLUE, "end"),
            (50, 40, "服務・卸貨－東側", "#555", "end")]:
        px, py = f.X(x0), f.Y(y0)
        ox = 18 if an == "start" else -18
        leader(s, px, py, px+ox, py-5, lab, 2.6, col, an, "bold")
    # 避車彎
    s.poly(f.P([(26, -3.6), (48, -3.6), (48, -8), (26, -8)]), fill="#fff",
           stroke=RED, stroke_width=0.5, stroke_dasharray="2 1.4")
    s.txt(f.X(37), f.Y(-5.4), "國小接送避車彎（不進基地）", 2.5, RED, "middle", "bold")
    # 開挖（L 形，避開中庭老樹）
    d = "M " + " L ".join(f"{f.X(a):.2f} {f.Y(b):.2f}" for a, b in
                          [(4, 17), (46, 17), (46, 56), (28, 56), (28, 34), (4, 34)]) + " Z"
    s.path(d, fill="none", stroke=RED, stroke_width=0.75, stroke_dasharray="2.6 1.6")
    s.txt(f.X(30), f.Y(50), "地下開挖範圍（B1 停車）", 2.8, RED, weight="bold")
    s.txt(f.X(30), f.Y(53.5), f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%", 2.4, RED)
    s.txt(f.X(30), f.Y(57), "L 形避開中庭既有樹根域", 2.4, RED)
    # 剖面線
    s.line(f.X(-40), f.Y(42), f.X(58), f.Y(42), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(-43), f.Y(43), "A", 4.0, INK, "middle", "bold")
    s.txt(f.X(61), f.Y(43), "A'", 4.0, INK, "middle", "bold")
    s.line(f.X(38), f.Y(-36), f.X(38), f.Y(70), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(38), f.Y(-39), "B", 4.0, INK, "middle", "bold")
    s.txt(f.X(38), f.Y(75), "B'", 4.0, INK, "middle", "bold")

