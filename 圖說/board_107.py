# 凹口在西南，三合院位於凹口「外」（基地外）
SITE = [(0, 0), (85, 0), (85, 74), (22, 74), (22, 52), (0, 52)]
A = 85*52 + (85-22)*22               # 5,806 ㎡〔鞋帶公式・圖推概算〕
BLK = [("展示・多功能演講廳", "1,440 ㎡ / 2F", 26, 30, 36, 20, "#f2e4c9"),
       ("文創工作坊（共同／個人工作室）", "1,632 ㎡ / 3F", 26, 54, 34, 16, "#e6dced"),
       ("辦公・會議・餐廳＋開放廚房・咖啡", "2,112 ㎡ / 3F", 66, 8, 16, 44, "#d6e6f2")]
FLR = {"展示・多功能演講廳": 2, "文創工作坊（共同／個人工作室）": 3,
       "辦公・會議・餐廳＋開放廚房・咖啡": 3}
FOOT = sum(w*h for *_, x, y, w, h, c in BLK)                # 1,968
G = sum(w*h*FLR[n] for n, _, x, y, w, h, c in BLK)          # 5,184
EXC = (24, 6, 56, 62)
D_AREA = EXC[2]*EXC[3]                                      # 3,472
PLAZA = (30, 6, 30, 20)                                     # 600 ㎡〔題目給定〕
assert PLAZA[2]*PLAZA[3] == 600
assert FOOT <= A*0.40 and G <= A*2.00, (FOOT, G)

def draw_plan(s, f, sp):
    # 3.6 M 無遮簷人行道（題目給定）
    s.poly(f.P([(-3.6, -3.6), (88.6, -3.6), (88.6, 77.6), (18.4, 77.6), (18.4, 55.6), (-3.6, 55.6)]),
           fill="#f3f1ea", stroke=GREY, stroke_width=0.4)
    s.txt(f.X(44), f.Y(-5.6), "3.6 M 無遮簷人行道（題目給定，非地方都審準則）", 2.8, "#666", "middle", "bold")
    # 周邊街廓
    s.rect(f.X(-40), f.Y(-30), f.L(130), f.L(22), fill=LGREY)
    s.txt(f.X(44), f.Y(-19), "北側都市道路", 3.0, "#555", "middle")
    s.rect(f.X(-40), f.Y(-30), f.L(32), f.L(112), fill=LGREY)
    s.txt(f.X(-24), f.Y(30), "西側都市道路", 3.0, "#555", "middle", rot=-90)
    s.rect(f.X(90), f.Y(-30), f.L(30), f.L(112), fill=LGREY)
    s.txt(f.X(105), f.Y(30), "東側都市道路", 3.0, "#555", "middle", rot=-90)
    s.rect(f.X(-40), f.Y(82), f.L(160), f.L(22), fill=LGREY)
    s.txt(f.X(44), f.Y(93), "南側都市道路", 3.0, "#555", "middle")
    # 歷史三合院（凹口外・基地外）
    s.poly(f.P([(-2, 54), (20, 54), (20, 76), (-2, 76)]), fill="#f5ece0", stroke=TAN, stroke_width=0.7)
    s.poly(f.P([(2, 56), (18, 56), (18, 62), (2, 62)]), fill="#e8dcc8", stroke=TAN, stroke_width=0.45)
    s.rect(f.X(2), f.Y(62), f.L(4), f.L(12), fill="#e8dcc8", stroke=TAN, stroke_width=0.45)
    s.rect(f.X(14), f.Y(62), f.L(4), f.L(12), fill="#e8dcc8", stroke=TAN, stroke_width=0.45)
    s.txt(f.X(10), f.Y(68), "三合院", 3.2, "#8a6a1f", "middle", "bold")
    s.txt(f.X(10), f.Y(72), "前埕", 2.8, "#8a6a1f", "middle")
    s.txt(f.X(10), f.Y(80.5), "一層歷史建物（位於邊界凹口「外」・基地外）", 2.7, RED, "middle", "bold")
    s.txt(f.X(10), f.Y(84.5), "⚠「歷史建物」不等於已完成法定歷史建築登錄", 2.4, RED, "middle")
    # 基地
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=0.95)
    s.txt(f.X(0), f.Y(-10), "基地界線（依題圖量取）　正文未給面積", 3.2, INK, weight="bold")
    s.txt(f.X(0), f.Y(-14.5), "A ≒ 85×52＋63×22 ＝ 5,806 ㎡〔鞋帶公式・圖推概算〕→ B≤2,322、F≤11,612", 2.7, RED)
    s.txt(f.X(22), f.Y(50), "凹口（三合院在此界線之外）", 2.6, RED, "start", "bold")
    # 捷運出口（東側基地內）
    s.rect(f.X(76), f.Y(56), f.L(8), f.L(10), fill="#dfe8f2", stroke=BLUE, stroke_width=0.7)
    s.txt(f.X(80), f.Y(61.5), "捷運", 2.8, BLUE, "middle", "bold")
    s.txt(f.X(80), f.Y(69.5), "捷運出口（基地內・題目給定）", 2.6, BLUE, "middle", "bold")
    s.txt(f.X(80), f.Y(73.5), "文創公共動線之起點", 2.4, BLUE, "middle")
    # 600 ㎡ 室外多功能廣場
    px, py, pw, ph = PLAZA
    s.rect(f.X(px), f.Y(py), f.L(pw), f.L(ph), fill="url(#plaza)", opacity=0.55,
           stroke=TAN, stroke_width=0.5)
    s.txt(f.X(px+pw/2), f.Y(py+ph/2-1.5), "室外多功能廣場 600 ㎡", 3.6, "#8a6a1f", "middle", "bold")
    s.txt(f.X(px+pw/2), f.Y(py+ph/2+2.5), "臨時展場〔題目給定〕", 2.7, "#8a6a1f", "middle")
    s.txt(f.X(px+pw/2), f.Y(py+ph/2+6), "無建物・避難集結", 2.4, "#8a6a1f", "middle")
    # 既有樹木（基地內）
    for tx, ty in [(64, 60), (70, 66), (58, 66), (66, 72)]:
        s.circ(f.X(tx), f.Y(ty), f.L(4.4), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.3)
    s.txt(f.X(64), f.Y(78), "既有樹木：本案選擇原地保留〔方案；原題亦准移植〕", 2.6, GREEN, "middle", "bold")
    # 量體
    for name, spec, x, y, w, h, col in BLK:
        s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill=col, stroke=INK, stroke_width=0.7)
        s.txt(f.X(x+w/2), f.Y(y+h/2)-1.4, name, 3.0 if len(name) > 12 else 3.6, INK, "middle", "bold")
        s.txt(f.X(x+w/2), f.Y(y+h/2)+2.6, spec, 2.6, "#555", "middle")
    # 視覺廊道：三合院前埕 → 廣場 → 捷運出口
    s.path(f'M {f.X(20):.2f} {f.Y(64):.2f} L {f.X(45):.2f} {f.Y(26):.2f} L {f.X(76):.2f} {f.Y(60):.2f}',
           fill="none", stroke=RED, stroke_width=0.9, stroke_dasharray="4 2")
    s.txt(f.X(45), f.Y(29.5), "文創公共動線：三合院前埕 → 600 ㎡ 廣場 → 捷運出口", 2.8, RED, "middle", "bold")
    # 出入口
    for x0, y0, lab, col, an in [
            (45, 0, "園區主入口－北側，接 3.6 M 人行道", RED, "start"),
            (85, 30, "卸貨・車道口－東側，避開三合院與主廣場", BLUE, "end"),
            (22, 62, "前埕側人行口－低層退讓、不壓迫三合院", TAN, "end")]:
        pxx, pyy = f.X(x0), f.Y(y0)
        ox = 20 if an == "start" else -20
        leader(s, pxx, pyy, pxx+ox, pyy-6, lab, 2.6, col, an, "bold")
    # 開挖
    ex, ey, ew, eh = EXC
    s.path(f'M {f.X(ex):.2f} {f.Y(ey):.2f} L {f.X(ex+ew):.2f} {f.Y(ey):.2f} '
           f'L {f.X(ex+ew):.2f} {f.Y(ey+eh):.2f} L {f.X(ex):.2f} {f.Y(ey+eh):.2f} Z',
           fill="none", stroke=RED, stroke_width=0.75, stroke_dasharray="2.6 1.6")
    leader(s, f.X(ex), f.Y(ey), f.X(ex)-24, f.Y(ey)-8,
           "地下開挖範圍（B1–B2 停車 120 輛＋機車 25）", 2.7, RED, "end", "bold")
    s.txt(f.X(ex)-24, f.Y(ey)-3.6, f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%", 2.4, RED, "end")
    s.txt(f.X(ex)-24, f.Y(ey)+0.8, "退離三合院側，不在凹口外開挖", 2.4, RED, "end")
    # 剖面線
    s.line(f.X(-44), f.Y(40), f.X(124), f.Y(40), stroke=INK, stroke_width=0.55,
           stroke_dasharray="5 1.8 1.4 1.8")
    s.txt(f.X(-48), f.Y(41), "A", 4.2, INK, "middle", "bold")
    s.txt(f.X(128), f.Y(41), "A'", 4.2, INK, "middle", "bold")
    s.line(f.X(45), f.Y(-32), f.X(45), f.Y(106), stroke=INK, stroke_width=0.55,
           stroke_dasharray="5 1.8 1.4 1.8")
    s.txt(f.X(45), f.Y(-36), "B", 4.2, INK, "middle", "bold")
    s.txt(f.X(45), f.Y(110), "B'", 4.2, INK, "middle", "bold")

