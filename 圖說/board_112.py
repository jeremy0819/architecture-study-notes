# ===== 基地幾何（公尺・題目給定 120×70）=====
W_, D_ = 120.0, 70.0
SITE = [(0, 0), (W_, 0), (W_, D_), (0, D_)]
A = W_*D_                                   # 8,400 ㎡〔題目給定〕
# 水圳斜穿：(80,0)→(65,70)，避讓半寬 6 M〔避讓帶寬為自訂方案，原題未給尺寸〕
def cx(y): return 80.0 - 15.0*(y/D_)
HW = 6.0

BLK = [
    ("研修教學棟", "1,760㎡ / 2F", 12, 8, 40, 22, "#e6dced"),
    ("住宿・研習棟", "2,640㎡ / 3F", 12, 40, 40, 22, "#d6e6f2"),
    ("公益展演・圖書", "2,080㎡ / 2F", 90, 16, 26, 40, "#f2e4c9"),
]
FOOT = sum(w*h for *_, x, y, w, h, c in BLK)          # 2,800
G = 40*22*2 + 40*22*3 + 26*40*2                        # 6,480
EXC = (10, 6, 46, 58)                                  # 2,668 ㎡
D_AREA = EXC[2]*EXC[3]

# 幾何自檢：量體與開挖不得侵入水圳避讓帶
for nm, _, x, y, w, h, _ in BLK:
    for yy in (y, y+h):
        assert x+w <= cx(yy)-HW or x >= cx(yy)+HW, f"{nm} 侵入水圳避讓帶"
for yy in (EXC[1], EXC[1]+EXC[3]):
    assert EXC[0]+EXC[2] <= cx(yy)-HW, "開挖範圍侵入水圳避讓帶"
assert FOOT <= A*0.55 and G <= A*3.60

def draw_plan(s, f, sp):
    # 周邊道路
    s.rect(f.X(-30), f.Y(-15), f.L(30), f.L(D_+35), fill=LGREY)        # 西 30M
    s.rect(f.X(-30), f.Y(-15), f.L(W_+40), f.L(15), fill=LGREY)        # 北 15M
    s.rect(f.X(-30), f.Y(D_), f.L(W_+40), f.L(20), fill=LGREY)         # 南 20M
    s.rect(f.X(W_), f.Y(-15), f.L(10), f.L(D_+35), fill=LGREY)         # 東 10M
    # 西側高架（約 10 M 高）
    s.rect(f.X(-22), f.Y(-15), f.L(9), f.L(D_+35), fill="#d8d4cc", stroke=GREY, stroke_width=0.4)
    for yy in range(-10, int(D_)+18, 14):
        s.rect(f.X(-19), f.Y(yy), f.L(3), f.L(3), fill="#b9b4aa", stroke=GREY, stroke_width=0.25)
    s.txt(f.X(-17.5), f.Y(D_*0.5), "西側高架道路（約 10 M 高・噪音震動明顯）", 3.0, RED, "middle", "bold", rot=-90)
    s.txt(f.X(-6), f.Y(D_*0.5), "西側 30 M 道路", 2.8, "#555", "middle", rot=-90)
    s.txt(f.X(W_/2), f.Y(-8), "北側 15 M 道路（對側住宅 7–9 層）", 2.9, "#555", "middle")
    s.txt(f.X(W_/2), f.Y(D_+11), "南側 20 M 道路（次入口）", 2.9, "#555", "middle")
    s.txt(f.X(W_+5), f.Y(D_*0.5), "東側 10 M 道路（安靜側）", 2.8, "#555", "middle", rot=-90)
    # 北側鄰里公園（基地外）
    s.rect(f.X(8), f.Y(-33), f.L(54), f.L(16), fill="url(#tree)", stroke=GREEN, stroke_width=0.4)
    s.txt(f.X(35), f.Y(-27), "鄰里公園（基地外）", 3.0, GREEN, "middle", "bold")
    s.txt(f.X(35), f.Y(-22.5), "隔 15 M 道路・借景不計入 A", 2.4, RED, "middle")
    # 基地界線
    s.poly(f.P(SITE), fill="#ffffff", stroke=INK, stroke_width=0.9)
    s.txt(f.X(2), f.Y(-3.2), "基地界線　東西 120 M／南北 70 M（矩形）", 3.0, INK, weight="bold")
    s.txt(f.X(2), f.Y(-7.6), "A＝120×70＝8,400 ㎡〔題目給定〕", 2.6, "#555")
    # 水圳線性綠廊（地面再現）
    band = [(cx(0)-HW, 0), (cx(0)+HW, 0), (cx(D_)+HW, D_), (cx(D_)-HW, D_)]
    s.poly(f.P(band), fill="url(#water)", opacity=0.75, stroke=BLUE, stroke_width=0.5)
    s.path("M "+" L ".join(f"{f.X(cx(y)):.2f} {f.Y(y):.2f}" for y in range(0, 71, 10)),
           fill="none", stroke=BLUE, stroke_width=0.9, stroke_dasharray="4 2")
    s.txt(f.X(cx(35)), f.Y(35), "水圳線性綠廊", 4.4, BLUE, "middle", "bold", rot=-78)
    s.txt(f.X(cx(35))+5.5, f.Y(35), "地面再現・優先避挖", 2.5, BLUE, "middle", rot=-78)
    s.txt(f.X(cx(58)), f.Y(60), "疑似水圳範圍：文資法 §57", 2.5, RED, "middle", "bold")
    s.txt(f.X(cx(62)), f.Y(64), "營建中發見應停工通報，審議完成前不得復工", 2.3, RED, "middle")
    # 東北角既有樹群（基地內・保留）
    for i, (tx, ty) in enumerate([(103, 5), (110, 8), (116, 4), (108, 12), (115, 11)]):
        s.circ(f.X(tx), f.Y(ty), f.L(4.2), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.3)
    s.txt(f.X(108), f.Y(17.5), "東北角既有樹群（基地內・原地保留）", 2.7, GREEN, "middle", "bold")
    # 西側緩衝帶（服務・停車・隔音）
    s.rect(f.X(0), f.Y(0), f.L(9), f.L(D_), fill="#efece6", stroke=GREY, stroke_width=0.35)
    s.txt(f.X(4.5), f.Y(D_*0.5), "隔音牆＋複層密植緩衝帶（服務・卸貨）", 2.6, "#666", "middle", rot=-90)
    # 量體
    for name, spec, x, y, w, h, col in BLK:
        s.rect(f.X(x), f.Y(y), f.L(w), f.L(h), fill=col, stroke=INK, stroke_width=0.6)
        s.txt(f.X(x+w/2), f.Y(y+h/2)-1.0, name, 3.8, INK, "middle", "bold")
        s.txt(f.X(x+w/2), f.Y(y+h/2)+3.2, spec, 2.6, "#555", "middle")
    # 公益廣場（水圳東側・南口）
    s.poly(f.P([(58, 2), (72, 2), (60, 68), (46, 68)]), fill="url(#plaza)", opacity=0.45,
           stroke=TAN, stroke_width=0.35)
    s.txt(f.X(60), f.Y(20), "公益廣場", 3.6, "#8a6a1f", "middle", "bold")
    s.txt(f.X(60), f.Y(24.5), "沿圳展開・避難集結", 2.4, "#8a6a1f", "middle")
    # 行道樹
    for xx in range(8, 118, 11):
        s.circ(f.X(xx), f.Y(-4), f.L(3.0), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.2)
    for xx in range(8, 118, 11):
        s.circ(f.X(xx), f.Y(D_+4), f.L(3.0), fill="url(#tree)", stroke="#6f9b5c", stroke_width=0.2)
    # 出入口
    for x, y, lab, col, an in [
            (35, 0, "主人行入口－對鄰里公園穿越", RED, "start"),
            (60, 70, "南側次入口－20 M 道路", RED, "start"),
            (0, 52, "車行・卸貨－西側緩衝帶（避高架匝道）", BLUE, "start"),
            (0, 60, "地下車道出入口（B1 停車）", "#7a5ea8", "start"),
            (120, 36, "東側安靜側・自行車", GREEN, "end")]:
        px, py = f.X(x), f.Y(y)
        ox = 16 if an == "start" else -16
        leader(s, px, py, px+ox, py-5, lab, 2.6, col, an, "bold")
    # 開挖範圍
    ex, ey, ew, eh = EXC
    s.path(f'M {f.X(ex):.2f} {f.Y(ey):.2f} L {f.X(ex+ew):.2f} {f.Y(ey):.2f} '
           f'L {f.X(ex+ew):.2f} {f.Y(ey+eh):.2f} L {f.X(ex):.2f} {f.Y(ey+eh):.2f} Z',
           fill="none", stroke=RED, stroke_width=0.7, stroke_dasharray="2.6 1.6")
    s.txt(f.X(ex+2), f.Y(ey+eh-4), "地下開挖範圍（B1 停車・汽30 機20）", 2.8, RED, weight="bold")
    s.txt(f.X(ex+2), f.Y(ey+eh-0.5),
          f"D＝{D_AREA:,} ㎡　D/A＝{D_AREA/A*100:.1f}%〔題目未給上限〕　全區止於水圳避讓帶西緣", 2.4, RED)
    # 剖面線
    s.line(f.X(-32), f.Y(32), f.X(W_+12), f.Y(32), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(-35), f.Y(33), "A", 4.0, INK, "middle", "bold")
    s.txt(f.X(W_+15), f.Y(33), "A'", 4.0, INK, "middle", "bold")
    s.line(f.X(32), f.Y(-17), f.X(32), f.Y(D_+22), stroke=INK, stroke_width=0.5,
           stroke_dasharray="5 1.6 1.4 1.6")
    s.txt(f.X(32), f.Y(-20), "B", 4.0, INK, "middle", "bold")
    s.txt(f.X(32), f.Y(D_+27), "B'", 4.0, INK, "middle", "bold")

