CJK = 'Microsoft JhengHei'  # 微軟正黑體
ACCENT = RGBColor(0x1F, 0x4E, 0x79)

doc = Document()

# ---- 預設字型（含東亞字型）----
def style_font(style_name, size=None, bold=None, color=None):
    st = doc.styles[style_name]
    st.font.name = CJK
    rpr = st.element.get_or_add_rPr()
    rf = rpr.get_or_add_rFonts()
    for a in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
        rf.set(qn(a), CJK)
    if size is not None: st.font.size = Pt(size)
    if bold is not None: st.font.bold = bold
    if color is not None: st.font.color.rgb = color

style_font('Normal', size=10.5)
for h, sz in (('Heading 1', 16), ('Heading 2', 13), ('Heading 3', 11.5)):
    style_font(h, size=sz, bold=True, color=ACCENT)
style_font('Title', size=26, bold=True, color=ACCENT)
style_font('Subtitle', size=13)

def run_font(run):
    run.font.name = CJK
    rpr = run._element.get_or_add_rPr()
    rf = rpr.get_or_add_rFonts()
    for a in ('w:ascii', 'w:hAnsi', 'w:eastAsia', 'w:cs'):
        rf.set(qn(a), CJK)

def P(text='', size=10.5, bold=False, italic=False, color=None, align=None, space_after=4):
    p = doc.add_paragraph()
    if align: p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    r = p.add_run(text)
    r.font.size = Pt(size); r.font.bold = bold; r.font.italic = italic
    if color: r.font.color.rgb = color
    run_font(r)
    return p

def bullets(items, size=10.5):
    for it in items:
        p = doc.add_paragraph(style='List Bullet')
        p.paragraph_format.space_after = Pt(2)
        r = p.add_run(it); r.font.size = Pt(size); run_font(r)

def H1(t):
    p = doc.add_heading(t, level=1);
    for r in p.runs: run_font(r)
    return p
def H2(t):
    p = doc.add_heading(t, level=2)
    for r in p.runs: run_font(r)
    return p
def H3(t):
    p = doc.add_heading(t, level=3)
    for r in p.runs: run_font(r)
    return p

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hdr = t.rows[0].cells
    for i, h in enumerate(headers):
        hdr[i].text = ''
        p = hdr[i].paragraphs[0]; r = p.add_run(h)
        r.font.bold = True; r.font.size = Pt(10); r.font.color.rgb = RGBColor(0xFF,0xFF,0xFF); run_font(r)
        shade(hdr[i], '1F4E79')
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].text = ''
            p = cells[i].paragraphs[0]; r = p.add_run(str(val))
            r.font.size = Pt(9.5); run_font(r)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t

def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement('w:shd'); sh.set(qn('w:val'),'clear'); sh.set(qn('w:fill'),hexcolor)
    tcPr.append(sh)

def box(text, fill='FFF2CC'):
    """重點框（單格表格）"""
    t = doc.add_table(rows=1, cols=1); t.style='Table Grid'
    c = t.rows[0].cells[0]; shade(c, fill); c.text=''
    p = c.paragraphs[0]; r = p.add_run(text); r.font.size=Pt(10); r.font.bold=True; run_font(r)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)

def pagebreak():
    doc.add_page_break()

def add_toc():
    p = doc.add_paragraph()
    run = p.add_run()
    fld1 = OxmlElement('w:fldChar'); fld1.set(qn('w:fldCharType'),'begin')
    instr = OxmlElement('w:instrText'); instr.set(qn('xml:space'),'preserve'); instr.text='TOC \\o "1-2" \\h \\z \\u'
    fld2 = OxmlElement('w:fldChar'); fld2.set(qn('w:fldCharType'),'separate')
    t = OxmlElement('w:t'); t.text='（在 Word 中按 Ctrl+A 後 F9 可更新目錄）'
    fld3 = OxmlElement('w:fldChar'); fld3.set(qn('w:fldCharType'),'end')
    run._r.append(fld1); run._r.append(instr); run._r.append(fld2); run._r.append(t); run._r.append(fld3)

